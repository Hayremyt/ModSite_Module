let LANG = "ru";

function detectLang(defaultLang) {
    const saved = localStorage.getItem("mods_lang");
    if (saved && I18N[saved]) return saved;
    const param = new URLSearchParams(location.search).get("lang");
    if (param && I18N[param]) return param;
    if (navigator.language && navigator.language.startsWith("ru")) return "ru";
    return defaultLang || "ru";
}

function setLang(lang) {
    LANG = I18N[lang] ? lang : "ru";
    localStorage.setItem("mods_lang", LANG);
    document.documentElement.lang = LANG;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (I18N[LANG][key]) el.textContent = I18N[LANG][key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (I18N[LANG][key]) el.placeholder = I18N[LANG][key];
    });
    const btn = document.getElementById("lang-label");
    if (btn) btn.textContent = LANG === "ru" ? "EN" : "RU";
    // подписчики (например, переключатель тем) перерисовывают свои подписи
    try { document.dispatchEvent(new CustomEvent("langchange")); } catch (e) { /* DOM недоступен (тесты без браузера) */ }
}

/** t(key, params) — перевод с подстановкой. */
function t(key, params) {
    let s = (I18N[LANG] && I18N[LANG][key]) || (I18N.ru && I18N.ru[key]) || key;
    if (params) {
        for (const [k, v] of Object.entries(params)) {
            s = s.split("{" + k + "}").join(String(v));
        }
    }
    return s;
}
